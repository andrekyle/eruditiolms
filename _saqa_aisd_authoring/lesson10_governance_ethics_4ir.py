    "<ul>"
    "<li><strong>Bias and fairness</strong> &mdash; e.g. a credit-scoring model that under-serves rural applicants.</li>"
    "<li><strong>Transparency and explainability</strong> &mdash; can you justify a decision to a customer or the Regulator?</li>"
    "<li><strong>Accountability</strong> &mdash; who is liable when a model causes harm?</li>"
    "<li><strong>Safety</strong> &mdash; robustness against adversarial inputs, hallucinations, prompt injection.</li>"
    "<li><strong>Privacy</strong> &mdash; minimise data, anonymise, use differential privacy where possible.</li>"
