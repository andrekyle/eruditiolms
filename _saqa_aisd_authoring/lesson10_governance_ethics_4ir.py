    "<h3>POPIA &mdash; eight conditions for lawful processing</h3>"
    "<ol>"
    "<li><strong>Accountability</strong> &mdash; the responsible party must ensure compliance.</li>"
    "<li><strong>Processing limitation</strong> &mdash; lawful, minimal, with consent or another legal basis.</li>"
    "<li><strong>Purpose specification</strong> &mdash; collect for a specific, explicitly defined purpose.</li>"
    "<li><strong>Further processing limitation</strong> &mdash; new uses must be compatible with the original purpose.</li>"
    "<li><strong>Information quality</strong> &mdash; data must be complete, accurate and up to date.</li>"
    "<li><strong>Openness</strong> &mdash; notify data subjects and keep a PAIA manual.</li>"
    "<li><strong>Security safeguards</strong> &mdash; technical and organisational controls; breach notification to the Regulator.</li>"
    "<li><strong>Data subject participation</strong> &mdash; right to access, correct and delete data.</li>"
    "</ol>"
    "<p><strong>Special personal information</strong> (race, health, biometrics, religion, sexual life, "
    "criminal behaviour, children's data) requires <em>extra</em> justification under sections 26&ndash;35. "
    "Cross-border transfers (s 72) need an adequate level of protection in the receiving country &mdash; "
    "this is the <strong>data sovereignty</strong> question that affects where you host an AI model.</p>"

